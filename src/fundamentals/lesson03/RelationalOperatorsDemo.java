package fundamentals.lesson03;

public class RelationalOperatorsDemo {

    public static void main(String[] args) {

        int age = 20;

        System.out.println("age > 18 : " + (age > 18));
        System.out.println("age < 18 : " + (age < 18));
        System.out.println("age >= 20 : " + (age >= 20));
        System.out.println("age <= 20 : " + (age <= 20));
        System.out.println("age == 20 : " + (age == 20));
        System.out.println("age != 20 : " + (age != 20));

        

        

    }
}